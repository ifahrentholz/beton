import AxeBuilder from '@axe-core/playwright'
import { expect, PUSH_ASK, test } from './fixtures'

// Freigabe-Leiste (WEB-007, löst die Karte aus WEB-018 ab) und Inbox (UX-001).

test('WEB-018 AC1 WEB-007 AC1: ⌘⏎ in der Leiste erlaubt und setzt fort, „Ablehnen“ liefert deny mit Grund', async ({ daemon, page }) => {
  const allowId = await daemon.session(PUSH_ASK, 'Erlauben')
  await daemon.login(page, `/s/${allowId}`)
  await page.getByLabel('Nachricht').fill('Bitte pushen')
  await page.getByLabel('Nachricht').press('Enter')
  const bar = page.getByRole('alertdialog')
  await expect(bar).toBeVisible()
  await expect(bar).toContainText('git push origin main')
  // Im Verlauf steht nur der Verweis auf die Leiste.
  await expect(page.getByTestId('approval-card')).toHaveAttribute('data-decided', 'false')
  await expect(page.getByTestId('approval-card').getByRole('button', { name: 'Erlauben' })).toHaveCount(0)
  await page.getByLabel('Nachricht').focus()
  // Eine gerade erschienene Card ist erst nach kurzer Sichtzeit per Taste entscheidbar.
  await page.waitForTimeout(500)
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(page.getByText('Push erledigt.')).toBeVisible()
  await expect(page.getByTestId('tool-card')).toHaveAttribute('data-status', 'completed')
  await expect(page.getByTestId('approval-card')).toHaveAttribute('data-decided', 'true')
  await expect(page.getByTestId('approval-notice')).toContainText('Erlaubt von dir')
  // Die Nachricht wurde nicht versehentlich gesendet.
  await expect(page.getByLabel('Nachricht')).toHaveValue('')

  const denyId = await daemon.session(PUSH_ASK, 'Ablehnen')
  await page.goto(`${daemon.url}/s/${denyId}`)
  await page.getByLabel('Nachricht').fill('Bitte pushen')
  await page.getByLabel('Nachricht').press('Enter')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Ablehnen …' }).click()
  await page.getByLabel('Grund für die Ablehnung, geht an den Agent').fill('Erst die Tests laufen lassen')
  await page.getByLabel('Grund für die Ablehnung, geht an den Agent').press('Enter')
  await expect(page.getByText('Push abgelehnt.')).toBeVisible()
  await expect(page.getByTestId('approval-card')).toContainText('Kommentar: Erst die Tests laufen lassen')
  const resolved = (await daemon.events(denyId)).find((e) => e.type === 'approval.resolved')
  expect(resolved?.payload).toMatchObject({ decision: 'deny', comment: 'Erst die Tests laufen lassen' })
})

test('WEB-018 AC2 WEB-007 AC2: entscheidet ein Client, zeigt der andere „entschieden von …“', async ({ daemon, browser }) => {
  const id = await daemon.session(PUSH_ASK, 'Zwei Clients')
  const ctxA = await browser.newContext()
  const ctxB = await browser.newContext()
  const a = await ctxA.newPage()
  const b = await ctxB.newPage()
  await daemon.login(a, `/s/${id}`)
  await daemon.login(b, `/s/${id}`)
  await a.getByLabel('Nachricht').fill('Bitte pushen')
  await a.getByLabel('Nachricht').press('Enter')
  await expect(a.getByRole('alertdialog')).toBeVisible()
  await expect(b.getByRole('alertdialog')).toBeVisible()
  await a.getByRole('alertdialog').getByRole('button', { name: 'Erlauben', exact: true }).click()
  // Bei B verschwindet die Freigabe mit Vermerk, wer entschieden hat.
  await expect(b.getByRole('alertdialog')).toHaveCount(0)
  await expect(b.getByTestId('approval-notice')).toContainText('Erlaubt von dir in einem anderen Fenster')
  await expect(b.getByTestId('approval-card')).toHaveAttribute('data-decided', 'true')
  await expect(b.getByTestId('approval-decided-by')).toContainText('von dir')
  await ctxA.close()
  await ctxB.close()
})

test('WEB-007 AC3: Die Leiste ist ein alertdialog ohne axe-Verstöße und per Tastatur bedienbar', async ({ daemon, page }) => {
  const id = await daemon.session(PUSH_ASK, 'Tastatur')
  await daemon.login(page, `/s/${id}`)
  await page.getByLabel('Nachricht').fill('Bitte pushen')
  await page.getByLabel('Nachricht').press('Enter')
  const bar = page.getByRole('alertdialog')
  await expect(bar).toBeVisible()
  const results = await new AxeBuilder({ page }).include('[data-testid="approval-bar"]').analyze()
  const serious = results.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')
  expect(serious.map((v) => `${v.id}: ${v.help}`)).toEqual([])
  // ⌘⇧A springt in die Leiste, Tab erreicht die Aktionen, Enter erlaubt.
  await page.getByLabel('Nachricht').focus()
  await page.keyboard.press('ControlOrMeta+Shift+A')
  await expect(bar).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(bar.getByRole('button', { name: 'Erlauben', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByText('Push erledigt.')).toBeVisible()
})

test('UX-001 AC1 AC2: Freigabe erscheint in der Inbox, „Erlauben“ dort setzt die pausierte Session fort', async ({ daemon, page }) => {
  const id = await daemon.session(PUSH_ASK, 'Im Hintergrund')
  // Niemand hat die Session offen: Eingabe über die API.
  await daemon.api('POST', `/v1/sessions/${id}/input`, { text: 'Bitte pushen' })
  await daemon.waitStatus(id, 'waiting_approval')
  await daemon.login(page, '/inbox')
  await expect(page.getByTestId('inbox-count')).toBeVisible()
  const row = page.getByTestId('inbox-item').filter({ hasText: 'Im Hintergrund' })
  await expect(row).toContainText('git push origin main')
  await expect(row).toHaveAttribute('data-status', 'open')
  await row.getByRole('button', { name: 'Erlauben', exact: true }).click()
  await daemon.waitStatus(id, 'idle')
  const events = await daemon.events(id)
  expect(events.some((e) => e.type === 'message.completed' && JSON.stringify(e.payload).includes('Push erledigt.'))).toBe(true)
  await page.getByRole('tab', { name: 'Erledigt' }).click()
  await expect(page.getByTestId('inbox-item').filter({ hasText: 'Im Hintergrund' })).toContainText('Erlaubt von')
})

test('UX-001: Tastatur in der Inbox (j/k, d mit Grund)', async ({ daemon, page }) => {
  const id = await daemon.session(PUSH_ASK, 'Per Tastatur')
  await daemon.api('POST', `/v1/sessions/${id}/input`, { text: 'Bitte pushen' })
  await daemon.waitStatus(id, 'waiting_approval')
  await daemon.login(page, '/inbox')
  await page.getByRole('tab', { name: /^Offen/ }).click()
  const row = page.getByTestId('inbox-item').filter({ hasText: 'Per Tastatur' })
  await expect(row).toBeVisible()
  // j/k bis zum Eintrag dieser Session.
  for (let i = 0; i < 10 && (await row.getAttribute('aria-current')) !== 'true'; i++) await page.keyboard.press('j')
  await expect(row).toHaveAttribute('aria-current', 'true')
  await page.keyboard.press('d')
  const reason = page.getByLabel('Grund für die Ablehnung, geht an den Agent')
  await expect(reason).toBeFocused()
  await reason.fill('Nicht heute')
  await reason.press('Enter')
  await daemon.waitStatus(id, 'idle')
  const resolved = (await daemon.events(id)).find((e) => e.type === 'approval.resolved')
  expect(resolved?.payload).toMatchObject({ decision: 'deny', comment: 'Nicht heute' })
})
